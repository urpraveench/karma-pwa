/** The idea for day `d`: the same all day, the next one tomorrow. */
export function ideaFor(d: DateStr): string {
  const [y, m, day] = d.split('-').map(Number);
  return IDEAS[Math.floor(Date.UTC(y, m - 1, day) / 864e5) % IDEAS.length];
}
